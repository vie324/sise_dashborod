-- ============================================================
-- 日報のメモ(notes)を保存できるようにする
-- ------------------------------------------------------------
-- 日報フォームは以前から `notes`（メモ/コメント）を入力・送信し、
-- 通知メールにも含めていたが、daily_reports に保存先カラムが無く
-- DB には永続化されていなかった（メール送信後に失われていた）。
-- このカラムを追加して保存できるようにする。
--
-- 追加のみ・デフォルト '' なので、既存コード／既存行に影響しない。
-- 既存DBに対しては、このマイグレーションを先に実行してから
-- notes を書き込むアプリ側コードをデプロイすること。
-- ============================================================

ALTER TABLE daily_reports
  ADD COLUMN IF NOT EXISTS notes TEXT NOT NULL DEFAULT '';

COMMENT ON COLUMN daily_reports.notes IS '日報のメモ/コメント（任意）。';
